function p = wig_params()
%WIG_PARAMS  小型地效飞行器（WIG UAV）纵向飞行动力学 —— 名义参数集
%
%   参考构型（锁定）：
%       翼展 b = 2.40 m   弦长 c = 0.40 m   机翼面积 S = 0.96 m^2
%       展弦比 AR = 6.0   质量 m = 12 kg    俯仰惯量 Iyy = 1.15 kg·m^2
%       地效飞行高度带 h = 0.05 ~ 0.50 m （h/b = 0.021 ~ 0.208）
%       巡航速度 V0 = 18 m/s，平飞配平升力系数 CL ≈ 0.62
%
%   坐标系约定（机体轴，右手系）：
%       x_b 指向机头，y_b 指向右翼，z_b 指向机腹（向下）
%       q 为俯仰角速度，抬头为正；M 为俯仰力矩，抬头为正： Iyy*dq/dt = M
%
%   状态量 x = [V; gam; alpha; q; h; T; de]（7 阶）
%       V     空速 [m/s]
%       gam   航迹倾角 [rad]
%       alpha 迎角 [rad]
%       q     俯仰角速度 [rad/s]
%       h     离地高度 [m]（地面/海面为 0）
%       T     发动机推力 [N]（一阶滞后状态）
%       de    升降舵偏角 [rad]（一阶舵机状态，正 = 后缘下偏 = 低头）
%   控制量 u = [de_cmd; dt_cmd]（升降舵指令 [rad]，油门指令 [0,1]）
%
%   本函数给出的是【名义模型】参数，即控制器内部使用的模型。
%   真实对象参数由 wig_truth_params.m 给出（含地效强度失配、RAM 效应、
%   升力非线性与参数摄动），二者之差即为自适应律需要在线补偿的不确定性。
%
%   用法： p = wig_params();

%% ===================== 环境与常量 =====================
p.name  = 'WIG-UAV-2400';
p.is_truth = false;         % 是否为"真实对象"参数集（由 wig_truth_params 置 true）
p.g     = 9.80665;          % 重力加速度 [m/s^2]
p.rho   = 1.225;            % 海平面空气密度 [kg/m^3]

%% ===================== 质量与惯量 =====================
p.m     = 12.0;             % 质量 [kg]
p.Iyy   = 1.15;             % 俯仰转动惯量 [kg·m^2]

%% ===================== 机翼几何与气动 =====================
p.b     = 2.40;             % 翼展 [m]
p.c     = 0.40;             % 平均气动弦长 [m]
p.S     = p.b*p.c;          % 机翼面积 [m^2]  (=0.96)
p.AR    = p.b^2/p.S;        % 展弦比          (=6.0)
p.e     = 0.85;             % 奥斯瓦尔德效率因子
p.a0    = 5.90;             % 二维升力线斜率 [1/rad] (≈2*pi*0.94)
p.aL0   = -3.0*pi/180;      % 零升迎角 [rad]（有弯度翼型，负值）
p.CD0   = 0.0250;           % 机翼废阻力系数（含机体、支架）
p.CD0t  = 0.0100;           % 平尾废阻力系数
p.Cmac  = -0.050;           % 机翼绕气动中心的俯仰力矩系数（低头为负）

%% ===================== 平尾（水平尾翼） =====================
p.lt    = 0.95;             % 尾力臂（CG 到尾气动中心）[m]
p.St    = 0.180;            % 平尾面积 [m^2]
p.bt    = 0.80;             % 平尾翼展 [m]
p.ARt   = p.bt^2/p.St;      % 平尾展弦比 (=3.556)
p.et    = 0.90;             % 平尾展弦比修正用效率因子
p.eta_t = 0.95;             % 平尾动压比 eta_t = q_t/q_inf
p.a0t   = 5.60;             % 平尾二维升力线斜率 [1/rad]
p.aL0t  = 0.0;              % 平尾零升迎角 [rad]（对称翼型）
p.it    = -2.0*pi/180;      % 平尾安装角 [rad]
p.a_de  = 1.60;             % 升降舵操纵效能 dCLt/d(de) [1/rad]
p.dz_t  = 0.30;             % 平尾相对机翼平面的垂向抬高量 [m]（尾翼在上方）
p.eps0  = 0.020;            % 下洗角常数项 [rad]
p.eps_a = 0.350;            % 下洗角梯度 d(eps)/d(alpha)

%% ===================== 质心相对位置 =====================
% 均为相对 CG 的机体轴坐标（x 向前为正，z 向下为正）
p.x_acw = +0.020;           % 机翼气动中心相对 CG 的纵向位置 [m]
p.z_acw =  0.000;           % 机翼气动中心垂向偏移 [m]
p.z_T   = -0.030;           % 推力线垂向偏移 [m]（负 = 推力线在 CG 上方）
p.i_T   =  0.0;             % 推力线安装角 [rad]

%% ===================== 机体附加俯仰力矩 =====================
p.Cm0f  =  0.004;           % 机体零升俯仰力矩系数
p.Cmaf  =  0.010;           % 机体俯仰力矩迎角导数

%% ===================== 地效（地面效应）模型 =====================
% 地效因子 kappa(h) = (h/b)^n / ( A + (h/b)^n ) ∈ (0,1]
%   kappa -> 1 : 远离地面，尾涡下洗完全保留（自由空气）
%   kappa -> 0 : 贴地飞行，地面镜像涡系抵消下洗，诱导阻力趋零、升力线斜率趋近二维值
% 模型形式与标定见 docs/ 理论分析报告 2.3 节：
%   以公开风洞/CFD 数据（h/b = 0.1 时诱导阻力下降约 60%、升力线斜率增大约 25%；
%   h/b = 0.5 时诱导阻力下降约 12% 等）拟合得到 A、n。
p.ge_A  = 0.0641;           % 形状参数 A
p.ge_n  = 1.4622;           % 指数 n
p.ge_src = 'analytic';      % 'analytic' | 'cfd'（cfd 时由 ANSYS 数据拟合覆盖 A、n）

%% ===================== 真实对象附加效应字段（名义值置零） =====================
% 这些字段在名义模型中不产生任何作用，仅用于保证"名义/真实"两套参数结构一致
p.k_ram  = 0.0;             % RAM 附加升力系数幅值（名义 = 0）
p.h_ram  = 0.25;            % RAM 特征高度 [m]
p.CLmax  = 1.0e6;           % 升力非线性软化上限（名义 = 无失速）
p.x_ram  = p.x_acw;         % RAM 附加力作用点（名义 = 机翼气动中心）

%% ===================== 动力与舵机 =====================
p.Tmax   = 35.0;            % 最大推力 [N]（推重比 0.30）
p.Tmin   = 0.0;             % 最小推力 [N]
p.tau_T  = 0.15;            % 发动机推力一阶时间常数 [s]
p.tau_e  = 0.05;            % 升降舵舵机一阶时间常数 [s]
p.de_max = 25*pi/180;       % 升降舵限幅 [rad]
p.de_rate= 120*pi/180;      % 升降舵最大角速率 [rad/s]

%% ===================== 巡航/工作点 =====================
p.V0    = 18.0;             % 名义巡航速度 [m/s]
p.h0    = 0.200;            % 名义巡航高度 [m]
p.h_min = 0.050;            % 地效区下边界 [m]
p.h_max = 0.500;            % 地效区上边界 [m]

%% ===================== 仿真设置 =====================
p.sim.dt     = 0.001;       % 被控对象积分步长 [s]（定步长 RK4）
p.sim.Ts     = 0.005;       % 飞控计算机采样周期 [s]（200 Hz，零阶保持）
p.sim.Tend   = 40.0;        % 默认仿真时长 [s]

%% ===================== 控制器参数 =====================
% 全部增益由"采样闭环极点分析 + 全包线网格搜索 + 非线性闭环验证"三步整定得到
% （见 run_00_clp / run_00_opt 与理论分析报告 4.6 节）。
% --- 外环：高度/航迹 ---
p.ctrl.k_h    = 2.00;       % 高度误差 -> 高度率修正增益 [1/s]
p.ctrl.k_hd   = 0.80;       % 高度率阻尼增益 [无量纲]
p.ctrl.gam_max= 12*pi/180;  % 航迹倾角限幅 [rad]
p.ctrl.tau_g  = 0.010;      % 航迹指令一阶滤波时间常数 [s]
% --- 内环：俯仰姿态（动态面控制 DSC） ---
p.ctrl.k_th   = 3.20;       % 俯仰角误差 -> 俯仰角速度指令增益 [1/s]
p.ctrl.tau_th = 0.100;      % 俯仰角指令滤波时间常数 [s]
p.ctrl.th_max = 20*pi/180;  % 俯仰角指令限幅（迎角包线保护）[rad]
p.ctrl.k_q    = 6.00;       % 俯仰角速度误差增益 [1/s]
p.ctrl.tau_q  = 0.010;      % 俯仰角速度指令滤波时间常数 [s]
% --- 速度环 ---
p.ctrl.k_V    = 1.53;       % 速度误差比例增益 [1/s]
p.ctrl.k_IV   = 0.42;       % 速度误差积分增益 [1/s^2]
p.ctrl.IV_max = 6.0;        % 积分限幅 [m/s]
% --- RBF 神经网络自适应 ---
% 自适应增益的量纲与采样稳定性约束（见理论分析报告 4.5 节）：
%   力矩通道回归向量 phi1 = phi_rbf * (qbar*S*c/Iyy)，其量级 g1 = qbar*S*c/Iyy ≈ 66 (1/s^2)
%   阻力通道回归向量 phi2 = phi_rbf / m，        其量级 g2 = 1/m        ≈ 0.083 (1/kg)
%   离散自适应律前向欧拉稳定条件： Ts * Gam * g * ||phi_rbf||^2 << 1
%   故 Gam1 必须远小于 Gam2（两者不可直接比较数值大小）。
p.ctrl.nn.Wmax  = 12.0;     % 权值范数投影上界
p.ctrl.nn.Gam1  = 0.005;    % 力矩通道自适应增益 (单位: 1/(s^2·rad))
p.ctrl.nn.Gam2  = 3.0;      % 阻力通道自适应增益 (单位: kg/(m·s))
p.ctrl.nn.nu_e  = 0.50;     % e-修正（e-modification）泄漏系数
p.ctrl.nn.c1_a  = [-0.02 0.20];   % 力矩通道输入范围: alpha [rad]
p.ctrl.nn.c1_q  = [-2.00 2.00];   % 力矩通道输入范围: q [rad/s]
p.ctrl.nn.c1_h  = [0.00 0.80];    % 力矩通道输入范围: h [m]
p.ctrl.nn.n1    = [5 3 5];        % 力矩通道 RBF 节点数 (alpha,q,h)
p.ctrl.nn.c2_a  = [-0.02 0.20];   % 阻力通道输入范围: alpha
p.ctrl.nn.c2_V  = [10.0 30.0];    % 阻力通道输入范围: V
p.ctrl.nn.c2_h  = [0.00 0.80];    % 阻力通道输入范围: h
p.ctrl.nn.n2    = [4 4 4];        % 阻力通道 RBF 节点数 (alpha,V,h)
% --- 鲁棒项 ---
% 注意：tanh 在零点附近的等效线性增益为 eta/Phi，该增益会叠加到相应回路的
% 比例增益上，因此 Phi 不宜取得过小（否则鲁棒项退化为高增益比例项，降低
% 相位裕度）。这里取 eta/Phi ≈ 3.1（力矩通道 2.50/0.80）与 1.5（速度通道 1.50/1.00）。
p.ctrl.eta_r  = 2.50;       % 力矩通道鲁棒增益 [rad/s^2]
p.ctrl.Phi_r  = 0.80;       % 力矩通道边界层厚度 [rad/s]
p.ctrl.eta_V  = 1.50;       % 速度通道鲁棒增益 [m/s^2]
p.ctrl.Phi_V  = 1.00;       % 速度通道边界层厚度 [m/s]
% 注：早期版本此处有 p.ctrl.k_aw = 1.50（执行器饱和抗积分饱和反馈增益），
%     经全代码检索确认【当前版本任何位置都未使用该字段】（wig_ctrl_update /
%     wig_dynamics 均无引用），故连同数值一并删除，避免读者误以为存在反算
%     抗积分饱和通道。抗积分饱和现由 wig_ctrl_update.m 中"执行器饱和时冻结
%     对应通道自适应更新"实现（sat_e / sat_t 判据）。
p.ctrl.use_grav_ff = true;  % 推力重力分量前馈（取自指令航迹角，避免正反馈）
% --- 开关 ---
p.ctrl.enable_nn   = true;  % 是否启用 RBF 神经网络自适应
p.ctrl.enable_rob  = true;  % 是否启用鲁棒项
p.ctrl.enable_alt  = true;  % 是否启用高度外环（false 则直接给俯仰角指令）

%% ===================== 传感器 =====================
p.sens.enable  = false;     % 是否叠加测量噪声
p.sens.sig_V   = 0.15;      % 空速噪声标准差 [m/s]
p.sens.sig_a   = 0.15*pi/180; % 迎角噪声 [rad]
p.sens.sig_q   = 0.30*pi/180; % 俯仰角速度噪声 [rad/s]
p.sens.sig_h   = 0.010;     % 高度噪声 [m]
p.sens.tau_f   = 0.02;      % 一阶低通滤波时间常数 [s]

%% ===================== 大气扰动 =====================
p.gust.enable = false;
p.gust.type   = '1-cos';    % '1-cos' | 'dryden'
p.gust.Wg     = 3.0;        % 离散阵风幅值 [m/s]
p.gust.t0     = 20.0;       % 阵风开始时刻 [s]
p.gust.tg     = 2.0;        % 阵风持续时间 [s]
p.gust.sig_u  = 1.5;        % Dryden 湍流强度 [m/s]
p.gust.Lu     = 60.0;       % Dryden 尺度长度 [m]
p.gust.seed   = 20260912;

end
