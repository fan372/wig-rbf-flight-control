    r.h1('4  RBF 神经网络自适应控制器设计')

    r.h2('4.1  控制架构')
    r.p('控制器采用三层串级结构，如图 4-1 所示：', first_indent=True)
    r.bullet('高度外环（运动学）：由高度误差与高度率生成航迹倾角指令 $\\gamma_c$；')
    r.bullet('姿态内环（动态面 + 动态逆 + RBF + 鲁棒项）：由 $\\gamma_c$ 生成俯仰角指令 '
             '$\\theta_c$，再由俯仰角速度回路解算出升降舵指令 $\\delta_{e,c}$；')
    r.bullet('速度回路（推力动态逆 + RBF + 鲁棒项 + 积分）：由速度误差生成油门指令 '
             '$\\delta_t$。')
    r.p('RBF 神经网络共两路：力矩通道（输入 $[\\alpha, q, h]$，5×3×5 = 75 个节点）'
        '在线估计俯仰力矩失配；阻力通道（输入 $[\\alpha, V, h]$，4×4×4 = 64 个节点）'
        '在线估计阻力失配。升力失配通过内环 $\\theta_c = \\gamma_c + \\alpha$ 中的'
        '迎角反馈自然补偿（因 $\\gamma = \\theta - \\alpha$ 为运动学恒等式，'
        '该结构使航迹角跟踪对升力误差不敏感），故无需单独设置升力通道网络。',
        first_indent=True)

    r.h2('4.2  高度外环与姿态内环')
    r.p('高度外环采用带高度率阻尼的比例导引律（高度率由 $\\dot{h} = V\\sin\\gamma$ 直接合成，'
        '无需数值微分）：', first_indent=True)
    r.eq(r'\gamma_d = \arcsin\!\left[\mathrm{sat}\!\left('
         r'\frac{\dot{h}_c - k_h e_h - k_{hd}\left(\dot{h} - \dot{h}_c\right)}{V},\ '
         r'\sin\gamma_{\max}\right)\right], \qquad e_h = h - h_c', number='(4-1)')
    r.p('姿态内环采用动态面控制（DSC）以避免对虚拟控制量求导：', first_indent=True)
    r.eq(r'\theta_d = \mathrm{sat}\!\left(\gamma_c + \alpha,\ \theta_{\max}\right), \qquad '
         r'\tau_{th}\dot{\theta}_c = \theta_d - \theta_c', number='(4-2)')
    r.eq(r'q_d = \dot{\theta}_c - k_\theta\left(\theta - \theta_c\right), \qquad '
         r'\tau_q \dot{q}_{cf} = \mathrm{sat}(q_d) - q_{cf}', number='(4-3)')
    r.eq(r'e_q = q - q_{cf}, \qquad \nu = \dot{q}_{cf} - k_q e_q', number='(4-4)')
    r.p('由 $\\gamma = \\theta - \\alpha$ 可知，式 (4-2) 使 $\\dot{\\theta} = '
        'k_\\theta(\\gamma_c - \\gamma)$，即俯仰角回路等价为一个航迹角跟踪回路。'
        '在配平点对该迎角-航迹角子系统线性化，可得其固有频率与阻尼比'
        '（$\\partial\\dot{\\gamma}/\\partial\\alpha = 3.90506\\ \\mathrm{s^{-1}}$，'
        '取自 results/log_stab.txt）：$\\omega_n = \\sqrt{3.90506\\,k_\\theta}$、'
        '$\\zeta = 3.90506/(2\\omega_n)$。'
        '例如出厂取值 $k_\\theta = 3.20\\ \\mathrm{s^{-1}}$ 对应 '
        '$\\omega_n \\approx 3.535\\ \\mathrm{rad/s}$、$\\zeta \\approx 0.552$。'
        '这为第 4.6 节的增益整定提供了直接依据。',
        first_indent=True)

    r.h2('4.3  动态逆控制律与 RBF 神经网络')
    r.p('记名义模型的零舵偏俯仰力矩为 $M_0(x)$、操纵导数为 $M_{\\delta_e}$，'
        '令 $f_0 = M_0/I_{yy}$、$b = M_{\\delta_e}/I_{yy}$，则升降舵控制律为：',
        first_indent=True)
    r.eq(r'\delta_{e,c} = \frac{1}{b}\left(\nu - f_0 - u_M - u_r\right)', number='(4-5)')
    r.p('其中 $u_M = W_1^{\\mathrm{T}}\\phi_1$ 为 RBF 网络对力矩失配的在线估计，'
        '$u_r$ 为鲁棒项。RBF 基函数与回归向量为：', first_indent=True)
    r.eq(r'\phi_j(z) = \exp\!\left(-\frac{1}{2}\sum_{i=1}^{3}'
         r'\frac{\left(z_i - c_{ij}\right)^{2}}{\sigma_i^{2}}\right), \qquad '
         r'\phi_1 = \phi(z_1)\,\frac{\bar{q}Sc}{I_{yy}}', number='(4-6)')
    r.p('中心 $c_j$ 在归一化坐标 $[-1,1]^3$ 上按网格均匀布置，宽度取网格间距，'
        '使相邻基函数在中心处重叠度约为 $e^{-1/2} = 0.61$。'
        '第 2 章的失配分析表明，力矩失配主要随 $\\alpha$、$q$、$h$ 变化，'
        '故取该三维输入。权值采用投影算子保证有界：', first_indent=True)
    r.eq(r'\dot{W}_1 = \mathrm{Proj}\!\left[\,\Gamma_1\left(\phi_1 e_q '
         r'- \nu_e\left|e_q\right| W_1\right)\right], \qquad '
         r'\dot{W}_2 = -\Gamma_2\left(\phi_2 e_V + \nu_e\left|e_V\right| W_2\right)',
         number='(4-7)')
    r.p('投影算子定义为：', first_indent=True)
    r.eq(r'\mathrm{Proj}(\tau) = \begin{cases} \tau, & \left\|W\right\| < W_{\max} \ \text{或}\ '
         r'W^{\mathrm{T}}\tau \leq 0 \\ \tau - \dfrac{W W^{\mathrm{T}}}{\left\|W\right\|^{2}}\tau, '
         r'& \text{其他} \end{cases}', number='(4-8)')
    r.p('注意两个通道自适应律的符号相反，原因在于估计量在控制律中的位置不同：'
        '力矩通道中 $u_M$ 以减号进入式 (4-5)，而速度通道中 $u_D$ 以加号进入式 (4-10)。'
        '若符号取错，估计量将变成正反馈，直接导致闭环发散——'
        '本文在调试阶段即观察到该现象（见 4.7 节）。', first_indent=True)

    r.h2('4.4  鲁棒项与 Lyapunov 稳定性证明')
    r.p('鲁棒项取饱和函数形式 $u_r = \\eta_r\\tanh(e_q/\\Phi_r)$，'
        '用于抵消神经网络逼近残差与外部扰动。将式 (4-5) 代入俯仰通道，'
        '并记真实对象与名义模型的力矩失配为 $\\Delta f = \\Delta M/I_{yy}$，得',
        first_indent=True)
    r.eq(r'\dot{e}_q = -k_q e_q + \left(\Delta f - u_M\right) - u_r '
         r'= -k_q e_q - \tilde{W}_1^{\mathrm{T}}\phi_1 + \varepsilon_1 - u_r', number='(4-9)')
    r.p('其中 $\\tilde{W}_1 = W_1 - W_1^{*}$ 为权值误差，$W_1^{*}$ 为理想权值，'
        '$\\varepsilon_1$ 为网络逼近残差且 $|\\varepsilon_1| \\leq \\varepsilon_N$。'
        '速度通道控制律与误差动态为：', first_indent=True)
    r.eq(r'T_{cmd} = \frac{m\left(\dot{V}_d + u_D - u_{rV}\right) + D_0 + '
         r'mg\sin\gamma_c}{\cos(\alpha + i_T)}', number='(4-10)')
    r.eq(r'\dot{e}_V = -k_V e_V - k_{IV} I_V - \tilde{W}_2^{\mathrm{T}}\phi_2 '
         r'+ \varepsilon_2 - u_{rV}', number='(4-11)')
    r.p('取 Lyapunov 函数：', first_indent=True)
    r.eq(r'V_L = \frac{1}{2}e_q^{2} + \frac{1}{2}\tilde{W}_1^{\mathrm{T}}'
         r'\Gamma_1^{-1}\tilde{W}_1 + \frac{1}{2}e_V^{2} + '
         r'\frac{1}{2}\tilde{W}_2^{\mathrm{T}}\Gamma_2^{-1}\tilde{W}_2 '
         r'+ \frac{1}{2}k_{IV} I_V^{2}', number='(4-12)')
    r.p('沿闭环轨迹求导，代入自适应律 (4-7) 后交叉项严格对消，得到：',
        first_indent=True)
    r.eq(r'\dot{V}_L \leq -k_q e_q^{2} - k_V e_V^{2} + \left|e_q\right|\left(\varepsilon_N + d_M\right) '
         r'- \eta_r e_q\tanh\!\left(\frac{e_q}{\Phi_r}\right) + \eta_V\,\Phi_V\,0.2785',
         number='(4-13)')
    r.p('利用不等式 $|z| - z\\tanh(z/\\Phi) \\leq 0.2785\\,\\Phi$，'
        '并取鲁棒增益满足 $\\eta_r \\geq \\varepsilon_N + d_M$（$d_M$ 为力矩扰动上界），'
        '则有：', first_indent=True)
    r.eq(r'\dot{V}_L \leq -2\lambda_{\min} V_L + c_0, \qquad '
         r'c_0 = 0.2785\left(\eta_r\Phi_r + \eta_V\Phi_V\right)', number='(4-14)')
    r.p('由此得到一致最终有界（UUB）结论：', first_indent=True)
    r.eq(r'\left\|e(t)\right\| \leq \sqrt{\frac{2V_L(0)}{\lambda_{\min}}'
         r'e^{-2\lambda_{\min} t} + \frac{c_0}{\lambda_{\min}}}', number='(4-15)')
    r.p('即跟踪误差以指数速率收敛到半径 $\\sqrt{c_0/\\lambda_{\\min}}$ 的残差集内。'
        '投影算子 (4-8) 保证 $\\|W(t)\\| \\leq W_{\\max}$ 对任意 $t \\geq 0$ 成立，'
        '且不破坏 $\\dot{V}_L$ 的负定性。高度外环为级联结构：'
        '由 $\\dot{e}_h = -k_h e_h + V(\\sin\\gamma - \\sin\\gamma_c)$ 可知，'
        '高度误差最终由内环航迹角跟踪误差界定，结合内环的 UUB 结论即得'
        '整个闭环系统的一致最终有界性。', first_indent=True)

    r.h2('4.5  采样实现与离散稳定性约束')
